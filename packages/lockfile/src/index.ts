import fs from 'node:fs/promises';
import path from 'node:path';
import YAML from 'yaml';
import { Lockfile, ResolvedPackage } from '@jmpm/shared';

export const LOCKFILE_NAME = 'jmpm-lock.yaml';

export async function readLockfile(projectDir: string): Promise<Lockfile | null> {
  const filePath = path.join(projectDir, LOCKFILE_NAME);
  try {
    const raw = await fs.readFile(filePath, 'utf8');
    const parsed = YAML.parse(raw) as Lockfile;
    if (parsed && typeof parsed === 'object') {
      return parsed;
    }
    return null;
  } catch {
    return null;
  }
}

export function sortObjectKeys<T extends Record<string, unknown>>(obj: T): T {
  const sorted = {} as T;
  const keys = Object.keys(obj).sort();
  for (const key of keys) {
    sorted[key as keyof T] = obj[key as keyof T];
  }
  return sorted;
}

export async function writeLockfile(
  projectDir: string,
  lockfile: Lockfile
): Promise<void> {
  const filePath = path.join(projectDir, LOCKFILE_NAME);

  const cleanLockfile: Lockfile = {
    lockfileVersion: lockfile.lockfileVersion || 1,
    dependencies: lockfile.dependencies ? sortObjectKeys(lockfile.dependencies) : {},
    devDependencies: lockfile.devDependencies ? sortObjectKeys(lockfile.devDependencies) : {},
    packages: sortObjectKeys(lockfile.packages || {})
  };

  const yamlContent = YAML.stringify(cleanLockfile, {
    indent: 2,
    lineWidth: 0
  });

  await fs.writeFile(filePath, `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# jmpm lockfile v1\n\n${yamlContent}`, 'utf8');
}

export function resolvedMapToLockfile(
  resolved: Map<string, ResolvedPackage>,
  directDeps: Record<string, string> = {},
  directDevDeps: Record<string, string> = {}
): Lockfile {
  const packages: Lockfile['packages'] = {};

  for (const [key, pkg] of resolved.entries()) {
    packages[key] = {
      version: pkg.version,
      resolved: pkg.resolved,
      integrity: pkg.integrity,
      dependencies: Object.keys(pkg.dependencies).length > 0 ? sortObjectKeys(pkg.dependencies) : undefined,
      bin: pkg.bin && Object.keys(pkg.bin).length > 0 ? sortObjectKeys(pkg.bin) : undefined
    };
  }

  return {
    lockfileVersion: 1,
    dependencies: sortObjectKeys(directDeps),
    devDependencies: sortObjectKeys(directDevDeps),
    packages: sortObjectKeys(packages)
  };
}

